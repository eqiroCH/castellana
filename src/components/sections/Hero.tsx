/** Headline words, each in its own line mask for the intro reveal. */
function Words({ text, accent = false, from = 0 }: { text: string; accent?: boolean; from?: number }) {
  const words = text.split(" ");
  return words.map((word, i) => (
    <Fragment key={word}>
      <span className="hx-mask">
        <span className="hx-word" data-hx={accent ? "word-em" : "word"} style={{ "--i": from + i } as CSSProperties}>
          {word}
        </span>
      </span>
      {i < words.length - 1 && " "}
    </Fragment>
  ));
}

