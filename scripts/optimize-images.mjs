#!/usr/bin/env node
/**
 * Image pipeline — run with `npm run images` (add `--force` to rebuild everything).
 *
 * 1. Downloads Unsplash originals listed in `scripts/image-manifest.mjs` into `.cache/images`.
 * 2. Crops (optional) and resizes every entry to WebP variants in `public/images/opt/`.
 * 3. Writes the typed registry `src/content/media.ts` and the photo credits in `CREDITS.md`.
 */
import { execFile } from "node:child_process";
import { existsSync } from "node:fs";
import { mkdir, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";
import sharp from "sharp";
import { images } from "./image-manifest.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const cacheDir = path.join(root, ".cache/images");
const outDir = path.join(root, "public/images/opt");
const force = process.argv.includes("--force");
const QUALITY = 78;
const DOWNLOAD_WIDTH = 2560;

async function sourceFile(entry) {
  if (entry.source.type === "local") return path.join(root, entry.source.path);
  const file = path.join(cacheDir, `${entry.source.id}.jpg`);
  if (existsSync(file)) return file;
  const url = `https://unsplash.com/photos/${entry.source.id}/download?force=true&w=${DOWNLOAD_WIDTH}`;
  // curl instead of fetch(): Unsplash's bot protection challenges Node's HTTP client.
  await promisify(execFile)("curl", ["-sSfL", "--max-time", "120", "-o", file, url]);
  console.log(`  ↓ ${entry.source.id}`);
  return file;
}

/** Returns the extract region for a crop with focus point, clamped to the image. */
function cropRegion(width, height, { aspect, focusX = 0.5, focusY = 0.5 }) {
  let w = width;
  let h = Math.round(width / aspect);
  if (h > height) {
    h = height;
    w = Math.round(height * aspect);
  }
  const left = Math.min(Math.max(Math.round(focusX * width - w / 2), 0), width - w);
  const top = Math.min(Math.max(Math.round(focusY * height - h / 2), 0), height - h);
  return { left, top, width: w, height: h };
}

const toHex = (n) => n.toString(16).padStart(2, "0");

async function processEntry(entry) {
  const file = await sourceFile(entry);
  const meta = await sharp(file).rotate().metadata();
  const region = entry.crop
    ? cropRegion(meta.width, meta.height, entry.crop)
    : { left: 0, top: 0, width: meta.width, height: meta.height };

  const base = () => sharp(file).rotate().extract(region);
  const widths = entry.widths.filter((w) => w <= region.width);
  if (widths.length === 0) widths.push(region.width);

  for (const w of widths) {
    const out = path.join(outDir, `${entry.slug}-${w}.webp`);
    if (!force && existsSync(out)) continue;
    await base().resize({ width: w }).webp({ quality: QUALITY, effort: 6 }).toFile(out);
  }

  const { dominant } = await base().resize({ width: 64 }).stats();
  const largest = widths[widths.length - 1];
  return {
    slug: entry.slug,
    width: largest,
    height: Math.round((largest * region.height) / region.width),
    widths,
    color: `#${toHex(dominant.r)}${toHex(dominant.g)}${toHex(dominant.b)}`,
    alt: entry.alt,
  };
}

function renderMediaTs(records) {
  const body = records
    .map(
      (r) =>
        `  ${JSON.stringify(r.slug)}: {\n` +
        `    width: ${r.width},\n` +
        `    height: ${r.height},\n` +
        `    widths: [${r.widths.join(", ")}],\n` +
        `    color: ${JSON.stringify(r.color)},\n` +
        `    alt: ${JSON.stringify(r.alt)},\n` +
        `  },`,
    )
    .join("\n");
  return `// AUTO-GENERATED by scripts/optimize-images.mjs — do not edit by hand.
// Add or change photos in scripts/image-manifest.mjs and run \`npm run images\`.

export type MediaEntry = {
  /** Intrinsic size of the largest variant. */
  width: number;
  height: number;
  /** Available WebP widths: /images/opt/<slug>-<width>.webp */
  widths: readonly number[];
  /** Dominant colour, used as placeholder background. */
  color: string;
  /** Default German alt text. */
  alt: string;
};

export const media = {
${body}
} as const satisfies Record<string, MediaEntry>;

export type MediaSlug = keyof typeof media;
`;
}

function renderCredits() {
  const seen = new Set();
  const rows = [];
  for (const entry of images) {
    if (entry.source.type !== "unsplash" || seen.has(entry.source.id)) continue;
    seen.add(entry.source.id);
    const used = images.filter((e) => e.source.type === "unsplash" && e.source.id === entry.source.id).map((e) => `\`${e.slug}\``);
    rows.push(
      `| ${entry.alt.replace(/ \(Symbolbild\)$/, "")} | [${entry.source.photographer}](https://unsplash.com/@${entry.source.handle}) | [unsplash.com/photos/${entry.source.id}](https://unsplash.com/photos/${entry.source.id}) | ${used.join(", ")} |`,
    );
  }
  return `# Bildnachweise

Diese Datei wird von \`scripts/optimize-images.mjs\` aus \`scripts/image-manifest.mjs\` erzeugt.

## Kundenfotos

Alle Fotos unter \`assets/photos/\`, \`public/images/team/\` und \`public/images/partners/\` stammen von der
Castellana Automobile AG (bisherige Website castellana.ch) bzw. den jeweiligen Partnern.

## Unsplash

Die folgenden Fotos werden unter der [Unsplash-Lizenz](https://unsplash.com/license) verwendet
(kostenlose kommerzielle Nutzung, Namensnennung freiwillig, hier dennoch dokumentiert).
Fahrzeugfotos auf Angebotskarten sind als «Symbolbild» gekennzeichnet.

| Motiv | Fotograf/in | Quelle | Verwendet als |
| --- | --- | --- | --- |
${rows.join("\n")}
`;
}

async function main() {
  await mkdir(cacheDir, { recursive: true });
  await mkdir(outDir, { recursive: true });

  const records = [];
  for (const entry of images) {
    records.push(await processEntry(entry));
    console.log(`  ✓ ${entry.slug}`);
  }

  // Remove variants that are no longer part of the manifest.
  const expected = new Set(records.flatMap((r) => r.widths.map((w) => `${r.slug}-${w}.webp`)));
  for (const file of await readdir(outDir)) {
    if (!expected.has(file)) await rm(path.join(outDir, file));
  }

  await writeFile(path.join(root, "src/content/media.ts"), renderMediaTs(records));
  await writeFile(path.join(root, "CREDITS.md"), renderCredits());
  console.log(`Done: ${records.length} images, ${expected.size} files in public/images/opt`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
